const C='assets-v3';
self.addEventListener('install',e=>{self.skipWaiting()});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==C).map(k=>caches.delete(k)))) )});
self.addEventListener('fetch',e=>{if(e.request.method!=='GET')return;
 e.respondWith(caches.open(C).then(async c=>{const m=await c.match(e.request);if(m)return m;
  const r=await fetch(e.request).catch(()=>null);
  if(r&&r.ok&&new URL(e.request.url).origin===location.origin)c.put(e.request,r.clone());
  if(r)return r;
  if(e.request.mode==='navigate')return (await c.match('index.html'))||Response.error();
  return Response.error()}))});
